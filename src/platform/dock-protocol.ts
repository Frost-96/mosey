import { z } from "zod";
const number = z.number().finite();
const count = number.int().nonnegative();
const text = z.string().max(4000);
const rect = z.strictObject({
  x: number,
  y: number,
  width: number,
  height: number,
});
const contour = z.strictObject({
  axisCount: count,
  fnv1a64: z.string().regex(/^[0-9a-f]{1,16}$/),
  minInwardCoordinate: number.nullable(),
  maxInwardCoordinate: number.nullable(),
});
const raw = z.strictObject({
  boundsPixels: rect.nullable(),
  inwardContourSummaryPixels: contour,
  nonzeroAlphaPixelCount: count,
  selectedPixelCount: count,
});
const largest = z.strictObject({
  boundsPixels: rect.nullable(),
  componentCount: count,
  inwardContourSummaryPixels: contour,
  selectedPixelCount: count,
});
const raster = z.strictObject({
  actualAlphaZero: z.boolean(),
  fullySelectedRaster: z.boolean(),
  height: count,
  width: count,
  largestComponent: largest,
  raw,
  orientation: z.enum(["bottom", "left", "right"]),
});
const snapshot = {
  acceptedComplete: count,
  acceptedCompleteSequence: count.nullable(),
  alphaAnalyzedCount: count,
  backpressureSkipped: count,
  callbackCount: count,
  callbackSilenceInvalidations: count,
  callbackTimeoutSeconds: number,
  candidateStatus: z.enum([
    "unavailable_or_stale",
    "current_from_source_age",
    "current_via_idle_heartbeat",
  ]),
  completeReceived: count,
  frameStatusCounts: z.record(z.string().regex(/^-?\d+$/), count),
  idleCallbacks: count,
  idleCurrentPolicy: z.boolean(),
  incompleteCallbacks: count,
  intervalSkipped: count,
  invalidationReason: text,
  lastAcceptedSourceAgeSeconds: number.nullable(),
  lastAcceptedSourceDisplayMachTicks: count.nullable(),
  lastCallbackAgeSeconds: number.nullable(),
  lastCompleteSourceAgeSeconds: number.nullable(),
  lastFrameStatusCode: number.int().nullable(),
  lastObservedStatus: text,
  lateComplete: count,
  latestCompleteSequence: count,
  maxObservedCallbackGapSeconds: number,
  pendingCompleteCount: count.max(1),
  pendingDiscardedOnInvalidation: count,
  pendingQueued: count,
  pendingReplaced: count,
  processedComplete: count,
  streamErrorCode: number.int().nullable(),
  supersededProcessed: count,
  upstreamDroppedFrames: z.literal("not_observable"),
  supportEdge: z.null(),
};
export const dockRecordSchema = z.discriminatedUnion("type", [
  z.strictObject({
    type: z.literal("environment"),
    appStatus: z.literal(false),
    buildMode: z.literal("optimized_-O"),
    bundleID: text.nullable(),
    bundlePath: text,
    callbackTimeoutSeconds: number,
    executable: text,
    idleCurrentPolicy: z.literal(true),
    machTimebaseDenom: count.positive(),
    machTimebaseNumer: count.positive(),
    orientation: z.enum(["bottom", "left", "right"]),
    os: text,
    outputLocalPath: z.null(),
    overlayRequested: z.literal(false),
    parentPID: count,
    permissionScope: text,
    processID: count.positive(),
    scenario: text,
    scenarioIsOperatorLabelOnly: z.literal(true),
    schedulingPolicy: z.literal("one_worker_plus_latest_complete_slot"),
    supportEdge: z.null(),
  }),
  z.strictObject({
    type: z.literal("dock_windows"),
    primaryDisplayID: count,
    supportEdge: z.null(),
    windows: z
      .array(
        z.strictObject({
          frame: rect,
          isOnScreen: z.boolean(),
          layer: number.int(),
          windowID: count,
        }),
      )
      .max(128),
  }),
  z.strictObject({
    type: z.literal("stream_configuration"),
    alphaThreshold: count.max(255),
    backgroundAlpha: z.literal(0),
    backingScale: number.positive(),
    callbackTimeoutSeconds: number,
    coordinateSpace: text,
    diagnosticMaxFrameAgeSeconds: number,
    filterContentRectPoints: rect,
    filterPointPixelScale: number,
    idleCurrentPolicy: z.literal(true),
    independentWindowFilter: z.literal(true),
    localIntervalGate: z.literal(false),
    pixelFormat: z.literal("BGRA"),
    primaryBoundsCGPoints: rect,
    primaryFrameAppKitPoints: rect,
    queueDepth: z.literal(3),
    rasterHeight: count.max(16384),
    rasterWidth: count.max(16384),
    requestedMinimumFrameIntervalSeconds: number,
    schedulingPolicy: z.literal("one_worker_plus_latest_complete_slot"),
    shouldBeOpaque: z.literal(false),
    supportEdge: z.null(),
    windowID: count,
    windowIsOnScreenDiagnosticOnly: z.boolean(),
  }),
  z.strictObject({
    type: z.literal("frame"),
    callbackAgeFromDisplaySeconds: number.nullable(),
    elapsed: number,
    frameContentRectPoints: rect.optional(),
    frameContentScale: number.optional(),
    frameScaleFactor: number.optional(),
    frameScreenRectDiagnostic: rect.optional(),
    frameSequence: count,
    frameStatus: z.literal(0),
    mappingValid: z.boolean(),
    processingEndMachTicks: count,
    processingSeconds: number,
    processingStartMachTicks: count,
    queueWaitSeconds: number,
    raster: raster.nullable(),
    receivedMachTicks: count,
    rejectionReason: text,
    sourceAgeAtProcessingEndSeconds: number.nullable(),
    sourceDisplayMachTicks: count.nullable(),
    status: z.enum(["complete_raster_diagnostic", "rejected"]),
    supportEdge: z.null(),
  }),
  z.strictObject({
    type: z.literal("heartbeat"),
    ...snapshot,
    elapsed: number,
  }),
  z.strictObject({
    type: z.literal("summary"),
    ...z.object(snapshot).partial().shape,
    status: text,
    supportEdge: z.null(),
    elapsed: number.optional(),
    productFeasibility: z.literal("unverified").optional(),
  }),
  z.strictObject({
    type: z.literal("unavailable"),
    status: text,
    shareableContentQueryAttempted: z.literal(false).optional(),
    errorCode: number.int().optional(),
    errorDomain: text.optional(),
    supportEdge: z.null(),
  }),
  z.strictObject({
    type: z.literal("stream_error"),
    errorDomain: text,
    errorCode: number.int(),
    supportEdge: z.null(),
  }),
]);
export const helperReceiptSchema = z.strictObject({
  sourceSHA256: z.string().regex(/^[a-f0-9]{64}$/),
  buildHelperSHA256: z.string().regex(/^[a-f0-9]{64}$/),
  swiftVersion: text,
  flags: z.array(text).max(16),
  signature: text,
});
